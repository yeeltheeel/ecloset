INSERT INTO season (name, min_temp, max_temp)
SELECT v.name, v.min_temp, v.max_temp
FROM (VALUES
          ('экстремальный мороз',   -50, -25),
          ('сильные морозы',        -25, -10),
          ('умеренные морозы',      -10,   0),
          ('прохладно',               0,  10),
          ('умеренно-тепло',         10,  15),
          ('умеренное лето',         15,  20),
          ('теплое лето',            20,  25),
          ('жара',                   25,  30),
          ('сильная жара',           30,  50),
          ('осень-зима-весна-лето', -20,  50),
          ('весна',                 -20,  30),
          ('осень',                 -20,  30),
          ('демисезон',               5,  15),
          ('лето',                   20,  50),
          ('зима',                  -50,  -5)
     ) AS v(name, min_temp, max_temp)
WHERE NOT EXISTS (SELECT 1 FROM season s WHERE s.name = v.name);